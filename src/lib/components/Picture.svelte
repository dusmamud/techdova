<script lang="ts">
	// Format waterfall: AVIF first, WebP second, JPG fallback. The
	// browser picks the first <source> type it supports, natively and
	// instantly — no JavaScript, and only one file is downloaded. The
	// <img> carries alt, dimensions and loading attributes and is the
	// universal fallback. Variants are generated from the PNG masters
	// by qa/convert-images.py; every image exists in all 3 formats.
	// The <picture> wrapper is display:contents so layout behaves
	// exactly as if the <img> stood alone.
	//
	// Responsive widths (audit finding P-3): each <source> and the
	// <img> carry a width-descriptor srcset built from the variants
	// generated by qa/generate-width-variants.py
	// ({base}-{w}w.{ext}, ladder 480/800/1200/1600 capped below the
	// natural width), plus the full-resolution original as the
	// largest entry. The caller passes `sizes` describing the
	// rendered slot at each breakpoint, so the browser picks the
	// smallest candidate that stays sharp at the device pixel ratio
	// (web.dev "Responsive images", MDN "Using responsive images in
	// HTML"). `sizes` must describe the real CSS slot — see each call
	// site. The default '100vw' is only a safety net for call sites
	// that forget; every call site passes an explicit value.
	//
	// Natural widths live here (not in the width/height props, which
	// some call sites set to display size, e.g. 96px thumbs, and
	// others omit): the catalogue of bases is closed (45 images),
	// verified against src/ by grep. An unknown base falls back to
	// the previous single-file behaviour so nothing can 404.
	const NATURAL_WIDTHS: Record<string, number> = {
		'/images/category-accessories': 1600,
		'/images/category-audio': 1600,
		'/images/category-computers': 1600,
		'/images/category-gaming': 1600,
		'/images/category-smartphones': 1600,
		'/images/category-smartwatches': 1600,
		'/images/hero-audio': 1920,
		'/images/hero-gaming': 1920,
		'/images/hero-main': 2048,
		'/images/promo-devices': 2048,
		'/images/product-airpods-pro': 1408,
		'/images/product-airpods-pro-2': 1408,
		'/images/product-airpods-pro-3': 1408,
		'/images/product-apple-watch-9': 1408,
		'/images/product-apple-watch-9-2': 1408,
		'/images/product-apple-watch-9-3': 1408,
		'/images/product-dell-xps-13': 1408,
		'/images/product-dell-xps-13-2': 1408,
		'/images/product-dell-xps-13-3': 1408,
		'/images/product-dualsense-controller': 1408,
		'/images/product-dualsense-controller-2': 1408,
		'/images/product-dualsense-controller-3': 1408,
		'/images/product-galaxy-s24': 1408,
		'/images/product-galaxy-s24-2': 1408,
		'/images/product-galaxy-s24-3': 1408,
		'/images/product-galaxy-watch-6': 1408,
		'/images/product-galaxy-watch-6-2': 1408,
		'/images/product-galaxy-watch-6-3': 1408,
		'/images/product-iphone-15-pro': 1408,
		'/images/product-iphone-15-pro-2': 1408,
		'/images/product-iphone-15-pro-3': 1408,
		'/images/product-macbook-air-m2': 1408,
		'/images/product-macbook-air-m2-2': 1408,
		'/images/product-macbook-air-m2-3': 1070,
		'/images/product-magsafe-charger': 1408,
		'/images/product-magsafe-charger-2': 1408,
		'/images/product-magsafe-charger-3': 1408,
		'/images/product-nintendo-switch': 1408,
		'/images/product-nintendo-switch-2': 1408,
		'/images/product-nintendo-switch-3': 1408,
		'/images/product-sony-wh1000xm5': 1408,
		'/images/product-sony-wh1000xm5-2': 1408,
		'/images/product-sony-wh1000xm5-3': 1408,
		'/images/product-usb-c-hub': 1408,
		'/images/product-usb-c-hub-2': 1408,
		'/images/product-usb-c-hub-3': 1408
	};
	const WIDTH_LADDER = [480, 800, 1200, 1600];

	let {
		base,
		alt,
		width,
		height,
		loading,
		fetchPriority,
		decoding = 'async',
		sizes = '100vw',
		class: className = ''
	}: {
		base: string; // path without extension, e.g. '/images/product-iphone-15-pro'
		alt: string;
		width?: number;
		height?: number;
		loading?: 'lazy' | 'eager';
		fetchPriority?: 'high' | 'low' | 'auto';
		decoding?: 'async' | 'sync' | 'auto';
		/** Rendered slot width per breakpoint, e.g. '(max-width: 1023px) 50vw, 320px'. */
		sizes?: string;
		class?: string;
	} = $props();

	const naturalWidth = $derived(NATURAL_WIDTHS[base]);
	const candidateWidths = $derived(
		naturalWidth ? [...WIDTH_LADDER.filter((w) => w < naturalWidth), naturalWidth] : []
	);

	function srcsetFor(ext: string): string {
		if (!naturalWidth) return `${base}.${ext}`;
		return candidateWidths
			.map((w) => (w === naturalWidth ? `${base}.${ext} ${w}w` : `${base}-${w}w.${ext} ${w}w`))
			.join(', ');
	}

	const avifSrcset = $derived(srcsetFor('avif'));
	const webpSrcset = $derived(srcsetFor('webp'));
	const jpgSrcset = $derived(srcsetFor('jpg'));
</script>

<picture class="contents">
	<source srcset={avifSrcset} {sizes} type="image/avif" />
	<source srcset={webpSrcset} {sizes} type="image/webp" />
	<img
		src="{base}.jpg"
		srcset={jpgSrcset}
		{sizes}
		{alt}
		{width}
		{height}
		{loading}
		fetchpriority={fetchPriority}
		{decoding}
		class={className}
	/>
</picture>
